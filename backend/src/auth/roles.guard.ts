import {
  CanActivate,          // Interface that defines the contract for a Guard
  ExecutionContext,     // Provides information about the current execution context
  Injectable,           // Allows NestJS to manage and inject the class as a dependency
} from '@nestjs/common';
import { Reflector } from '@nestjs/core';   // Allows reading metadata from methods or classes
import { Role } from '@prisma/client';      // Enum generated by Prisma with the roles defined in the schema

import { PrismaService } from '../prisma/prisma.service';   // Provides access to the database through Prisma
import { ROLES_KEY } from './roles.decorator';              // Metadata key used to identify the roles required by an endpoint

@Injectable()
export class RolesGuard implements CanActivate {      // Implements the CanActivate interface, which requires a canActivate() method

  constructor(
    private readonly reflector: Reflector,
    private readonly prisma: PrismaService,
  ) {}

  async canActivate(context: ExecutionContext): Promise<boolean> {    // This method is automatically called by NestJS when the Guard is executed; Returns true to allow access, false to deny it (HTTP 403)

    const requiredRoles = this.reflector.getAllAndOverride<Role[]>(   // Reads the required roles from metadata (expected type: Role[])
      ROLES_KEY,
      [                         // Order matters: method metadata takes priority over class metadata
        context.getHandler(),   // First, checks the endpoint method
        context.getClass(),     // Then, checks the controller class
      ],
    );      // This retrieves the metadata previously set by @Roles() through SetMetadata()

    if (!requiredRoles) {     // No roles required, access allowed
      return true;
    }

    const request = context.switchToHttp().getRequest();    // Gets the current HTTP request

    const userId = request.user?.id;    // Gets the authenticated user's ID (set by JwtStrategy); // ?. (optional chaining) returns undefined instead of throwing an error if request.user is null or undefined

    if (!userId) {     // Denies access if no authenticated user ID is available
      return false;
    }

    const user = await this.prisma.user.findUnique({
      where: {
        id: userId,
      },
      select: {
        role: true,     // Retrieves only the user's current role from the database
      },
    });

    if (!user) {        // Denies access if the user no longer exists
      return false;
    }

    return requiredRoles.includes(user.role);   // Allows access if the user's role is among the required roles
  }
}
